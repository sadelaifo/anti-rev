#!/bin/sh
# authz-embed-qemu-hash.sh — pin a trusted caller build by name + SHA-256.
#
# Updates kmod2/module/gate_trusted_hashes.h so the kernel gate trusts ONE
# specific binary (e.g. your gate-enabled qemu-aarch64-static, or the shipped
# `vr` live-upgrade tool) instead of any file that merely shares the basename.
# Rebuild the module after running this.
#
# Usage:
#   authz-embed-qemu-hash.sh <binary> [name] <out-header>
#     <binary>     the exact file to pin (its SHA-256 is embedded)
#     [name]       name the gate matches at runtime (default: basename <binary>)
#     <out-header> path to gate_trusted_hashes.h (written atomically)
#
# MERGE semantics: any EXISTING pins in <out-header> for OTHER names are
# preserved; an existing pin for the SAME name is replaced.  So you can pin
# several builds with repeated runs, e.g.:
#     authz-embed-qemu-hash.sh .../qemu-aarch64-static qemu-aarch64-static H
#     authz-embed-qemu-hash.sh /usr/local/bin/vr       vr                  H
# Written atomically (temp + mv) so a failure never truncates the header
# (cf. the authz-embed-pubkey.sh gotcha).  Tolerant of headers written by an
# older build (old arev_* identifiers) when reading existing pins.
set -eu

if [ $# -eq 2 ]; then
	BIN=$1; NAME=$(basename "$1"); OUT=$2
elif [ $# -eq 3 ]; then
	BIN=$1; NAME=$2; OUT=$3
else
	echo "usage: $0 <binary> [name] <out-header>" >&2
	exit 2
fi

[ -r "$BIN" ] || { echo "error: cannot read $BIN" >&2; exit 1; }

# 32-byte SHA-256 as lowercase hex (portable: sha256sum or 'shasum -a 256').
if command -v sha256sum >/dev/null 2>&1; then
	HEX=$(sha256sum "$BIN" | cut -d' ' -f1)
elif command -v shasum >/dev/null 2>&1; then
	HEX=$(shasum -a 256 "$BIN" | cut -d' ' -f1)
else
	echo "error: need sha256sum or shasum" >&2; exit 1
fi
[ "${#HEX}" -eq 64 ] || { echo "error: bad digest '$HEX'" >&2; exit 1; }

# --- collect existing pins (NAME HEX64 per line), tolerant of old identifiers.
# State machine: an entry opens on a line carrying `{ "<name>", {` and closes on
# the first following `} },`; byte values are any 0xNN tokens in between.  The
# `{ NULL, { 0 } }` sentinel has no quoted name, so it is naturally skipped.
PINS=""
if [ -f "$OUT" ]; then
	PINS=$(awk '
		match($0, /"[^"]*"[ \t]*,[ \t]*{/) {
			s = substr($0, RSTART)
			sub(/".*/, "", s); name = s          # unused guard
			if (match($0, /"[^"]*"/)) {
				name = substr($0, RSTART+1, RLENGTH-2)
				inentry = 1; hex = ""
			}
		}
		inentry == 1 {
			t = $0
			while (match(t, /0x[0-9A-Fa-f][0-9A-Fa-f]/)) {
				hex = hex substr(t, RSTART+2, 2)
				t = substr(t, RSTART+RLENGTH)
			}
			if (index($0, "} },") > 0) {
				if (length(hex) == 64) print name " " tolower(hex)
				inentry = 0
			}
		}
	' "$OUT")
fi

# Emit one C initialiser entry: `\t{ "name", {\n\t\t0x.., ... } },`
emit_entry() {
	_name=$1; _hex=$2
	printf '\t{ "%s", {\n' "$_name"
	printf '%s\n' "$_hex" | sed -E 's/(..)/0x\1, /g' | fold -s -w 48 \
		| sed 's/^/\t\t/; s/ $//'
	printf '\t} },\n'
}

TMP=$(mktemp "${OUT}.XXXXXX")
trap 'rm -f "$TMP"' EXIT
{
	cat <<H
/*
 * gate_trusted_hashes.h — GENERATED by authz-embed-qemu-hash.sh.  Do not hand-
 * edit unless adding more pinned entries.  Pins a caller build by name + exact
 * SHA-256 (see the module's gate.c az_h / vcf_ctl_caller_ok).  Rebuild the
 * module after regenerating.  Last pinned: $NAME ($BIN)
 */
#ifndef VCACHEFS_GATE_TRUSTED_HASHES_H
#define VCACHEFS_GATE_TRUSTED_HASHES_H

struct vcf_trusted_hash {
	const char	*name;
	unsigned char	sha256[32];
};

static const struct vcf_trusted_hash vcf_trusted_hashes[] = {
H
	# preserved pins for OTHER names (replace same-name below)
	printf '%s\n' "$PINS" | while IFS=' ' read -r pn ph; do
		[ -n "$pn" ] || continue
		[ "$pn" = "$NAME" ] && continue
		emit_entry "$pn" "$ph"
	done
	# the new/updated pin
	emit_entry "$NAME" "$HEX"
	cat <<H
	{ NULL, { 0 } },
};

#endif /* VCACHEFS_GATE_TRUSTED_HASHES_H */
H
} > "$TMP"
mv "$TMP" "$OUT"
trap - EXIT
echo "pinned '$NAME' = $HEX"
echo "preserved other pins: $(printf '%s\n' "$PINS" | awk -v n="$NAME" '$1&&$1!=n{print $1}' | paste -sd, - 2>/dev/null || true)"
echo "wrote $OUT — rebuild the module."
